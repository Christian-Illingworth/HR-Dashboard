// Builds the dashboard's shadow-root stylesheet from the design kit (research R2, tasks T031).
//
// The kit's CSS files are read-only inputs: this script never writes to design-kit/. It:
//   - puts `:host { all: initial; }` first, so SharePoint's inherited styles stop at the boundary;
//   - rewrites `:root` and `html` to `:host`, and `body` to `.cu-root` (the app's root element);
//   - drops the kit's @font-face rules, which are declared once at document level instead
//     (@font-face inside a shadow root isn't reliably applied; see src/fonts.ts).
// Output: src/styles/shadow.generated.ts (bundled into the library) and dist/shadow.css.
//
// Usage: node scripts/build-shadow-css.mjs [--check]   (--check fails if the output is stale)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
export const KIT_FILES = ['tokens.css', 'base.css', 'components.css'].map((f) => here(`../../../design-kit/css/${f}`));
export const PROJECT_FILE = here('../src/styles/project.css');
const GENERATED_TS = here('../src/styles/shadow.generated.ts');
const DIST_CSS = here('../dist/shadow.css');

const ROOT_SELECTOR = /(^|[\s>+~(,])(:root|html|body)(?=$|[\s.:#[>+~,)])/g;

const scopeToShadow = {
  postcssPlugin: 'hrd-scope-to-shadow',
  AtRule: {
    'font-face': (atRule) => atRule.remove(),
  },
  Rule(rule) {
    rule.selectors = rule.selectors.map((sel) =>
      sel.replace(ROOT_SELECTOR, (_m, pre, name) => pre + (name === 'body' ? '.cu-root' : ':host')),
    );
  },
};

export function buildShadowCss() {
  const parts = [...KIT_FILES, PROJECT_FILE].map((file) => readFileSync(file, 'utf8'));
  const host = ':host { all: initial; display: block; }\n';
  const css = parts.map((source) => postcss([scopeToShadow]).process(source, { from: undefined }).css).join('\n');
  return host + css;
}

function moduleSource(css) {
  return (
    '// GENERATED by scripts/build-shadow-css.mjs from design-kit/css and src/styles/project.css.\n' +
    '// Do not edit. Run `npm run build:css -w @hrd/dashboard-ui` after changing either.\n' +
    `export const shadowCss = ${JSON.stringify(css)};\n`
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const css = buildShadowCss();
  const source = moduleSource(css);
  if (process.argv.includes('--check')) {
    const current = readFileSync(GENERATED_TS, 'utf8');
    if (current !== source) {
      console.error('src/styles/shadow.generated.ts is out of date. Run: npm run build:css -w @hrd/dashboard-ui');
      process.exit(1);
    }
    console.log('shadow CSS is up to date');
  } else {
    writeFileSync(GENERATED_TS, source);
    mkdirSync(here('../dist'), { recursive: true });
    writeFileSync(DIST_CSS, css);
    console.log(`wrote shadow CSS (${css.length} characters)`);
  }
}

export { moduleSource };
